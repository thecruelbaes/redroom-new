/**
 * Реестр правовых норм.
 *
 * Зачем это отдельный модуль с полем confidence, а не константы по коду.
 *
 * При проверке спецификации выяснилось, что часть сумм и номеров частей в ней
 * неверна, а главный «продающий» аргумент (трансграничная передача через
 * Google Analytics = до 6 млн) в КоАП вообще не имеет отдельного состава.
 * Ошибка в номере статьи в первом письме стоит сделки, поэтому цитаты закона
 * здесь — данные с уровнем доверия, а не строки в шаблоне.
 *
 * Правило, которое обеспечивает `assertReportable`:
 * в клиентский отчёт попадают ТОЛЬКО нормы со статусом 'verified'.
 * Всё остальное можно обсуждать голосом, но не печатать под своей подписью.
 *
 * ВАЖНО ПРО ТЕКУЩЕЕ СОСТОЯНИЕ. В окружении, где собирался этот модуль,
 * сетевая политика закрыла consultant.ru, garant.ru, pravo.gov.ru и прочие
 * первоисточники (403 на уровне прокси). Проверка выполнена по нескольким
 * независимым вторичным источникам с перекрёстной сверкой, и это НЕ то же
 * самое, что сверка с текстом кодекса. Поэтому уровень 'verified' здесь
 * означает «дословная формулировка нормы получена и совпала у независимых
 * источников», а всё спорное честно помечено 'probable' или 'disputed'.
 *
 * Перед первым письмом клиенту: открыть КонсультантПлюс с обычной машины,
 * сверить каждую запись и проставить checkedAt. Это работа на 30 минут,
 * и она защищает от единственной ошибки, которая убивает сделку молча.
 */

export type LegalConfidence =
  /** Дословная формулировка получена, независимые источники совпали. */
  | 'verified'
  /** Два и более независимых источника согласны, дословный текст не получен. */
  | 'probable'
  /** Источники противоречат друг другу. В отчёт нельзя ни в каком виде. */
  | 'disputed'
  /** Распространённое утверждение, которое проверку не прошло. */
  | 'debunked';

/** Диапазон штрафа в рублях, либо null — если для этой категории состава нет. */
export type FineRange = readonly [min: number, max: number] | null;

export interface Fines {
  readonly citizen: FineRange;
  readonly official: FineRange;
  /** У ИП собственной колонки часто нет — ФЗ-420 приравнял их к юрлицам. */
  readonly entrepreneur: FineRange;
  readonly company: FineRange;
}

export interface LegalNorm {
  readonly id: string;
  /** Что обязан делать оператор. */
  readonly duty: string;
  /** Норма, устанавливающая обязанность. */
  readonly source: string;
  /** Норма, устанавливающая ответственность. */
  readonly liability: string;
  readonly fines: Fines | null;
  readonly confidence: LegalConfidence;
  /** Чем подтверждено и что осталось перепроверить. */
  readonly note: string;
  /** Дата сверки с первоисточником. null — сверки ещё не было. */
  readonly checkedAt: string | null;
}

