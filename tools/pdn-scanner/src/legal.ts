const BY_ID = new Map(NORMS.map((n) => [n.id, n]));

export function getNorm(id: string): LegalNorm {
  const norm = BY_ID.get(id);
  if (!norm) throw new Error(`Неизвестная норма: ${id}`);
  return norm;
}

export function allNorms(): readonly LegalNorm[] {
  return NORMS;
}

/**
 * Можно ли цитировать норму в документе, который увидит клиент.
 * Отчёт обязан звать это перед печатью любой ссылки на закон.
 */
export function isReportable(id: string): boolean {
  return getNorm(id).confidence === 'verified';
}

/** Можно ли называть сумму штрафа. Строже, чем isReportable. */
export function isFineReportable(id: string): boolean {
  const n = getNorm(id);
  return n.confidence === 'verified' && n.fines !== null;
}

/**
 * Защита от случайной публикации непроверенной нормы.
 * Вызывается генератором отчёта, а не проверками.
 */
export function assertReportable(id: string): LegalNorm {
  const n = getNorm(id);
  if (n.confidence !== 'verified') {
    throw new Error(
      `Норма ${id} имеет статус '${n.confidence}' и не может попасть в клиентский отчёт. ` +
        `Сверьте её с первоисточником и проставьте checkedAt. Причина: ${n.note.split('\n')[0]}`,
    );
  }
  return n;
}

/** Нормы, ждущие сверки с первоисточником. Печатается в конце скана. */
export function pendingVerification(): readonly LegalNorm[] {
  return NORMS.filter((n) => n.checkedAt === null && n.confidence !== 'debunked');
}

export function formatFine(range: FineRange): string {
  if (!range) return '—';
  const fmt = (v: number) => v.toLocaleString('ru-RU');
  return `${fmt(range[0])}–${fmt(range[1])} ₽`;
}
